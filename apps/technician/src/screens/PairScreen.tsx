import React, { useState } from "react";
import {
  View,
  Text,
  TextInput,
  StyleSheet,
  SafeAreaView,
  KeyboardAvoidingView,
  Platform,
  Alert,
} from "react-native";
import * as Notifications from "expo-notifications";
import * as Device from "expo-device";
import { colors, spacing, typography } from "../theme";
import { Button } from "../components/Button";
import { pairDevice, ApiError } from "../api";
import { saveCredentials } from "../storage";

export function PairScreen({ onPaired }: { onPaired: () => void }) {
  const [code, setCode] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handlePair() {
    const cleanCode = code.trim();
    if (!/^\d{6}$/.test(cleanCode)) {
      setError("Please enter the 6-digit code provided by the office.");
      return;
    }

    setLoading(true);
    setError(null);

    try {
      // 1. Check & request push token if supported
      let pushToken: string | undefined;
      if (Device.isDevice) {
        try {
          const { status: existingStatus } = await Notifications.getPermissionsAsync();
          let finalStatus = existingStatus;
          if (existingStatus !== "granted") {
            const { status } = await Notifications.requestPermissionsAsync();
            finalStatus = status;
          }
          if (finalStatus === "granted") {
            const tokenData = await Notifications.getExpoPushTokenAsync().catch(() => null);
            if (tokenData?.data) {
              pushToken = tokenData.data;
            }
          }
        } catch {
          // Push notifications optional in early setup
        }
      }

      const deviceName = `${Device.manufacturer || ""} ${Device.modelName || "Android"}`.trim();

      // 2. Pair device with server
      const result = await pairDevice({
        code: cleanCode,
        deviceName,
        pushToken,
      });

      // 3. Save secret securely
      await saveCredentials({
        deviceId: result.deviceId,
        secret: result.secret,
        technicianName: result.technician.name,
      });

      onPaired();
    } catch (err) {
      if (err instanceof ApiError) {
        setError(err.message);
      } else {
        setError("Unable to connect to BITA server. Check your internet connection.");
      }
    } finally {
      setLoading(false);
    }
  }

  return (
    <SafeAreaView style={styles.container}>
      <KeyboardAvoidingView
        behavior={Platform.OS === "ios" ? "padding" : "height"}
        style={styles.inner}
      >
        <View style={styles.content}>
          <Text style={styles.brand}>BITA</Text>
          <Text style={styles.title}>Link this phone</Text>
          <Text style={styles.subtitle}>
            Enter the 6-digit pairing code generated by the office in the staff register.
          </Text>

          <TextInput
            style={[styles.input, error ? styles.inputError : null]}
            placeholder="000000"
            placeholderTextColor={colors.ink3}
            keyboardType="number-pad"
            maxLength={6}
            value={code}
            onChangeText={(val) => {
              setCode(val);
              setError(null);
            }}
            autoFocus
          />

          {error && <Text style={styles.errorText}>{error}</Text>}

          <Button
            title={loading ? "Verifying..." : "Link phone"}
            onPress={handlePair}
            loading={loading}
            disabled={code.trim().length !== 6 || loading}
            style={styles.button}
          />
        </View>

        <Text style={styles.footerNote}>
          Technicians do not need passwords. Once linked, this phone securely receives assigned jobs.
        </Text>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  container: {
    flex: 1,
    backgroundColor: colors.background,
  },
  inner: {
    flex: 1,
    padding: spacing.xl,
    justifyContent: "space-between",
  },
  content: {
    marginTop: spacing.xxl,
  },
  brand: {
    fontSize: 20,
    fontWeight: "700",
    letterSpacing: 2,
    color: colors.ink,
    marginBottom: spacing.sm,
  },
  title: {
    ...typography.header,
    marginBottom: spacing.xs,
  },
  subtitle: {
    ...typography.sub,
    lineHeight: 18,
    marginBottom: spacing.xl,
  },
  input: {
    backgroundColor: colors.surface,
    borderWidth: 1,
    borderColor: colors.line,
    borderRadius: 8,
    paddingHorizontal: spacing.lg,
    paddingVertical: spacing.md,
    fontSize: 28,
    fontFamily: "monospace",
    textAlign: "center",
    letterSpacing: 8,
    color: colors.ink,
    marginBottom: spacing.sm,
    minHeight: 56,
  },
  inputError: {
    borderColor: colors.bad,
  },
  errorText: {
    color: colors.bad,
    fontSize: 13,
    marginBottom: spacing.md,
    textAlign: "center",
  },
  button: {
    marginTop: spacing.md,
  },
  footerNote: {
    ...typography.caption,
    textAlign: "center",
    lineHeight: 16,
    color: colors.ink3,
    marginBottom: spacing.md,
  },
});
